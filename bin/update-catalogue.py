#!/usr/bin/env python3
"""Write catalogue.js from the nf-core pipeline catalogue (pipelines.json from nf-core/website).

Usage: bin/update-catalogue.py path/to/pipelines.json
Get the file with:
  git clone --depth 1 --filter=blob:none --sparse https://github.com/nf-core/website
  git -C website sparse-checkout set --no-cone /public/pipelines.json
"""

import datetime
import json
import pathlib
import sys

# Released, but still shown as in development.
DEV = {"references"}

src = json.loads(pathlib.Path(sys.argv[1]).read_text())["remote_workflows"]
out = {}
for p in sorted(src, key=lambda p: p["name"]):
    if p.get("archived"):
        continue
    rels = [r for r in p.get("releases", []) if r["tag_name"] != "dev"]
    latest = (
        max(rels, key=lambda r: r["published_at"])["tag_name"]
        if rels and p["name"] not in DEV
        else None
    )
    out[p["name"]] = {"desc": (p.get("description") or "").strip(), "rel": latest}

stamp = datetime.date.today().isoformat()
js = (
    f"// Generated by bin/update-catalogue.py on {stamp} from the nf-core pipeline catalogue. Do not edit by hand.\n"
    f"// Active pipelines: description and latest release (null while in development).\n"
    f'const CATALOGUE_DATE = "{stamp}";\n'
    f"const CATALOGUE = {json.dumps(out, indent=0, ensure_ascii=False)};\n"
)
pathlib.Path(__file__).resolve().parent.parent.joinpath("catalogue.js").write_text(js)
print(f"{len(out)} pipelines, {sum(1 for v in out.values() if v['rel'])} released")
